"""
scripts/review_stage9.py
========================
Stage 9 Review: Research Paper completeness check.

Validates:
  A) Paper source files exist
  B) All sections are present (no missing TODOs blocking submission)
  C) All figures referenced in paper exist on disk
  D) All tables input'd exist on disk
  E) Bibliography has all required entries
  F) All [FILL] placeholders have been replaced (submission-ready check)

Usage: python scripts/review_stage9.py
"""
import os, sys, re
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))

PASS  = "[PASS]"
FAIL  = "[FAIL]"
WARN  = "[WARN]"
issues = []

def check(label, condition, detail="", warn=False):
    if condition:
        print(f"  {PASS} {label}" + (f" — {detail}" if detail else ""))
    elif warn:
        print(f"  {WARN} {label}" + (f" — {detail}" if detail else ""))
    else:
        print(f"  {FAIL} {label}" + (f" — {detail}" if detail else ""))
        issues.append(label)

print("\n" + "="*65)
print("  STAGE 9: Research Paper Review")
print("="*65)

PAPER_DIR  = "paper"
TEX_FILE   = os.path.join(PAPER_DIR, "main.tex")
BIB_FILE   = os.path.join(PAPER_DIR, "references.bib")
FIGS_DIR   = "results/figures"
TABLES_DIR = "results/tables"

# ----------------------------------------------------------------
# A: Source files
# ----------------------------------------------------------------
print("\n  [A] Paper Source Files")
check("paper/main.tex exists",       os.path.exists(TEX_FILE))
check("paper/references.bib exists", os.path.exists(BIB_FILE))
check("paper/ directory exists",     os.path.isdir(PAPER_DIR))

# ----------------------------------------------------------------
# B: Section structure
# ----------------------------------------------------------------
print("\n  [B] Paper Section Structure")
if os.path.exists(TEX_FILE):
    tex = open(TEX_FILE, encoding="utf-8").read()
    required_sections = [
        (r"\\section{Introduction}",           "Section 1: Introduction"),
        (r"\\section{Related Work}",            "Section 2: Related Work"),
        (r"\\section{Problem Setup}",           "Section 3: Problem Setup"),
        (r"\\section{Methodology}",             "Section 4: Methodology"),
        (r"\\section{Experiments and Results}", "Section 5: Experiments"),
        (r"\\section{Discussion}",              "Section 6: Discussion"),
        (r"\\section{Conclusion}",              "Section 7: Conclusion"),
        (r"\\begin{abstract}",                  "Abstract"),
        (r"\\bibliography{references}",         "Bibliography command"),
        (r"\\bibliographystyle",                "Bibliography style"),
    ]
    for pattern, label in required_sections:
        check(label, bool(re.search(pattern, tex)))

    # Key content checks
    key_content = [
        ("explanation equivalence",     "Equivalence metric defined"),
        ("lie budget",                  "Lie budget defined"),
        ("pre-registered",              "Pre-registration mentioned"),
        ("NHANES",                      "Dataset named"),
        ("SHAP",                        "SHAP cited"),
        ("LIME",                        "LIME cited"),
        ("Wilcoxon",                    "Statistical test named"),
        ("\\\\begin{definition}",       "Formal definition present"),
        ("N\\^\\*",                     "N* notation used"),
    ]
    for pattern, label in key_content:
        check(label, bool(re.search(pattern, tex, re.IGNORECASE)))

    # Count TODOs
    todos = re.findall(r'%.*TODO', tex)
    check("TODOs present (sections to write)", len(todos) > 0,
          f"{len(todos)} TODO blocks for team members", warn=False)
    check("No [FILL] placeholders (submission-ready)",
          "[FILL]" not in tex,
          f"{tex.count('[FILL]')} placeholders remain" if "[FILL]" in tex else "Clean",
          warn="[FILL]" in tex)

# ----------------------------------------------------------------
# C: Figures referenced in paper all exist
# ----------------------------------------------------------------
print("\n  [C] Figures Referenced in Paper")
if os.path.exists(TEX_FILE):
    tex = open(TEX_FILE, encoding="utf-8").read()
    fig_refs = re.findall(r'\\includegraphics\[.*?\]\{(.*?)\}', tex)
    for ref in fig_refs:
        # Resolve relative path from paper/ dir
        path = os.path.normpath(os.path.join(PAPER_DIR, ref))
        exists = os.path.exists(path)
        # Figures are generated by run_analysis.py after Stage 7 —
        # treat as warning until final experiment completes
        check(f"Figure '{os.path.basename(ref)}' exists",
              exists,
              path if exists else "Run run_analysis.py after Stage 7 to generate",
              warn=not exists)

# ----------------------------------------------------------------
# D: Tables \input'd exist
# ----------------------------------------------------------------
print("\n  [D] Tables Input'd in Paper")
if os.path.exists(TEX_FILE):
    tex = open(TEX_FILE, encoding="utf-8").read()
    table_refs = re.findall(r'\\input\{(.*?)\}', tex)
    for ref in table_refs:
        path = os.path.normpath(os.path.join(PAPER_DIR, ref))
        # Also check with .tex extension
        if not path.endswith('.tex'):
            path += '.tex'
        exists = os.path.exists(path)
        check(f"Table '{os.path.basename(ref)}' exists",
              exists,
              path if exists else f"MISSING (run run_analysis.py first)",
              warn=not exists)

# ----------------------------------------------------------------
# E: Bibliography completeness
# ----------------------------------------------------------------
print("\n  [E] Bibliography Entries")
required_citekeys = [
    "ribeiro2016lime",
    "lundberg2017shap",
    "adadi2018peeking",
    "shokri2021privacy",
    "ghalme2021strategic",
    "slack2020fooling",
    "goodman2017european",
    "wachter2017counterfactual",
    "johnson2014national",
    "pedregosa2011sklearn",
    "wilcoxon1945individual",
    "ada2023standards",
]
if os.path.exists(BIB_FILE):
    bib = open(BIB_FILE, encoding="utf-8").read()
    for key in required_citekeys:
        check(f"  @...{{{key}...}}", key in bib)

# ----------------------------------------------------------------
# F: Venue + submission readiness
# ----------------------------------------------------------------
print("\n  [F] Submission Readiness")
checklist = [
    (os.path.exists(TEX_FILE),                        "main.tex written"),
    (os.path.exists(BIB_FILE),                        "references.bib complete"),
    (os.path.exists(os.path.join(FIGS_DIR, "fig1_reporting_gaps.png")),
                                                       "Fig 1 exists"),
    (os.path.exists(os.path.join(FIGS_DIR, "fig2_main_result.png")),
                                                       "Fig 2 (main result) exists"),
    (os.path.exists(os.path.join(FIGS_DIR, "fig8_config_heatmap.png")),
                                                       "Fig 8 (heatmap) exists"),
    (os.path.exists(os.path.join(TABLES_DIR, "table4_main_results.tex")),
                                                       "Table 4 (main results) in LaTeX"),
    (os.path.exists("docs/analysis_plan.md"),          "Pre-registration doc exists"),
]
for cond, label in checklist:
    check(label, cond, warn=not cond)

# ----------------------------------------------------------------
# SUMMARY
# ----------------------------------------------------------------
print("\n" + "="*65)
print("  SUMMARY")
print("="*65)

fill_count = 0
if os.path.exists(TEX_FILE):
    tex = open(TEX_FILE, encoding="utf-8").read()
    fill_count = tex.count("[FILL]")
    todo_count = len(re.findall(r'%.*TODO', tex))

if issues:
    print(f"\n  {FAIL} {len(issues)} blocking issue(s):")
    for i in issues:
        print(f"    - {i}")
else:
    print(f"\n  {PASS} All structural checks passed!")

if fill_count > 0:
    print(f"\n  {WARN} {fill_count} [FILL] placeholders remain")
    print("        Fill these after Stage 7 (final experiment) completes.")
if 'todo_count' in dir() and todo_count > 0:
    print(f"\n  {WARN} {todo_count} TODO blocks for team members")
    print("        Complete per the writing schedule in roadmap/09_paper_writing.md")

print("\n  Paper files:")
print(f"    {TEX_FILE}")
print(f"    {BIB_FILE}")
print(f"\n  Next step: Fill [FILL] placeholders once final experiment completes")
print(f"  Then compile with: pdflatex paper/main.tex && bibtex paper/main")
print()
